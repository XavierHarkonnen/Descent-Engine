template<typename Generator, typename G>
class Random : Detail {
private:
	static_assert(type::traits<G>::is_unsigned, "Generator type must be unsigned");

	template<typename T>
	static constexpr u64 COUNT = (type::traits<T>::bits + type::traits<G>::bits - 1) / type::traits<G>::bits;

	Generator& generator() {
		return static_cast<Generator&>(*this);
	}

	template<typename T>
	T next() {
		static_assert(type::traits<T>::is_integer, "next type must be an integer");

		using U = typename type::traits<T>::to_unsigned;
		
		U result = 0;
		for (u64 i = 0; i < COUNT<T>; ++i) {
			U value = static_cast<U>(generator().next());

			if constexpr (type::traits<T>::bits < type::traits<G>::bits) {
				value >>= (type::traits<G>::bits - type::traits<T>::bits);
			}

			result |= static_cast<U>(value << (i * type::traits<G>::bits));
		}

		return static_cast<T>(result);
	}

	template<typename T>
	T urange(T min, T max) {
		static_assert(type::traits<T>::is_unsigned, "urange type must be unsigned");

		sys_assert(min < max, "Minimum must be less than maximum");

		T range = max - min - 1;
		if (range == 0)
			return min;

		T mask = (~T(0)) >> bit::clz(range);

		T random;
		do {
			random = next<T>() & mask;
		} while (random > range);

		return min + random;
	}

	template<typename T>
	T irange(T min, T max) {
		static_assert(type::traits<T>::is_signed, "irange type must be signed");

		sys_assert(min < max, "Minimum must be less than maximum");

		using U = typename type::traits<T>::to_unsigned;

		U range = (static_cast<U>(max) - static_cast<U>(min)) - 1;
		if (range == 0)
			return min;
	
		U mask = type::traits<U>::max >> bit::clz(range);

		U random;
		do {
			random = next<U>() & mask;
		} while (random > range);

		return min + static_cast<T>(random);
	}

	template <typename T>
	T normal() {
		static_assert(type::traits<T>::is_float, "Attempted to get unsupported type");

		using D = Detail::normal<T>;

		constexpr T R = T(3.442619855899);

		for (;;) {
			const u64 bits = next<u64>();
			auto hz = D::sample(bits);
			auto iz = D::index(bits);

			if (math::abs(hz) < D::K[iz])
				return static_cast<T>(hz) * D::W[iz];
		
			const T x = static_cast<T>(hz) * D::W[iz];

			if (iz == 0) {
				T xx;
				T yy;

				do {
					xx = -math::log(uniform<T>()) / R;
					yy = -math::log(uniform<T>());
				} while (yy + yy < xx * xx);

				return hz > 0 ? R + xx : -R - xx;
			}

			const T y = D::F[iz] + uniform<T>() * (D::F[iz - 1] - D::F[iz]);

			if (y < math::exp(T(-0.5) * x * x))
				return x;
		}
	}

	template <typename T>
	T exponential() {
		static_assert(type::traits<T>::is_float, "Attempted to get unsupported type");

		using D = Detail::exponential<T>;

		constexpr T R = T(7.697117470131487);

		for (;;) {
			u64 bits = next<u64>();

			auto jz = D::sample(bits);
			auto iz = D::index(bits);

			if (jz < D::K[iz])
				return static_cast<T>(jz) * D::W[iz];

			if (iz == 0)
				return R - math::log(uniform<T>());

			const T x = static_cast<T>(jz) * D::W[iz];

			const T y = D::F[iz] + uniform<T>() * (D::F[iz - 1] - D::F[iz]);

			if (y < math::exp(-x))
				return x;
		}
	}

public:
	// Seeds a generator
	void seed(u64 seed) {
		generator().init(seed);
	}

	// Generates a uniformly distributed boolean or integer over its natural range.
	template<typename T>
	T get() {
		static_assert(type::traits<T>::is_bool || type::traits<T>::is_integer, "Attempted to get unsupported type");

		if constexpr (type::traits<T>::is_bool) {
			return (next<G>() >> (type::traits<G>::bits - 1)) != 0;
		}
		else if constexpr (type::traits<T>::is_integer) {
			return next<T>();
		}
	}

	// Generates a uniformly distributed integer in the range [min, max).
	template<typename T>
	T get(T min, T max) {
		static_assert(type::traits<T>::is_integer, "Attempted to get unsupported type");

		if constexpr (type::traits<T>::is_unsigned) {
			return urange(min, max);
		}
		else if constexpr (type::traits<T>::is_signed) {
			return irange(min, max);
		}
	}

	// Generates a uniformly distributed floating-point number in the range [0.0, 1.0).
	template<typename T>
	T uniform() {
		static_assert(type::traits<T>::is_float, "Attempted to get unsupported type");

		if constexpr (type::traits<T>::bits == 32) {
			return f32(get<u32>() >> 8) * 0x1.0p-24f;
		}
		else if constexpr (type::traits<T>::bits == 64) {
			return f64(get<u64>() >> 11) * 0x1.0p-53;
		}
	}

	// Generates a uniformly distributed floating-point number in the range [min, max).
	template<typename T>
	T uniform(T min, T max) {
		return min + (max - min) * uniform<T>();
	}
	
	// Generates a normally distributed floating-point number with the specified mean and standard deviation
	template<typename T>
	T normal(T mean, T std_dev) {
		return normal<T>() * std_dev + mean;
	}

	// Generates an exponentially distributed floating-point number with the specified lambda
	template<typename T>
	T exponential(T lambda) {
		return exponential<T>() / lambda;
	}
};

class WyRand : public Random<WyRand, u64> {
	friend class Random<WyRand, u64>;

private:
	u64 _state;

	u64 next() {
		_state += u64(0xA0761D6478BD642F);

		u64 high;
		u64 low = math::mul(_state ^ u64(0xE7037ED1A0B428DB), _state, high);

		return (low ^ high);
	}

	void init(u64 seed) {
		_state = seed;
	}
};

